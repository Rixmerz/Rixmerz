def get_token():
    for var in ("GH_TOKEN", "GITHUB_TOKEN"):
        if os.environ.get(var):
            return os.environ[var]
    try:
        return subprocess.run(["gh", "auth", "token"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        sys.exit("No token: set GH_TOKEN or sign in with `gh auth login`.")


TOKEN = None


def request(url, data=None):
    headers = {"Authorization": f"Bearer {TOKEN}", "User-Agent": "profile-cards", "Accept": "application/vnd.github+json"}
    if data is not None:
        data = json.dumps(data).encode()
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.loads(resp.read().decode()), resp.headers
    except urllib.error.HTTPError as e:
        sys.exit(f"Error {e.code} on {url}: {e.read().decode()[:200]}")


def rest(path):
    return request("https://api.github.com" + path)


def rest_all(path):
    """GET every page of a list endpoint."""
    items, page = [], 1
    while True:
        sep = "&" if "?" in path else "?"
        body, _ = rest(f"{path}{sep}per_page=100&page={page}")
        items += body
        if len(body) < 100:
            return items
        page += 1


def graphql(query, variables):
    body, _ = request("https://api.github.com/graphql", {"query": query, "variables": variables})
    if "errors" in body:
        sys.exit(f"GraphQL error: {body['errors']}")
    return body["data"]


def commit_count(repo):
    body, headers = rest(f"/repos/{repo}/commits?per_page=1")
    m = re.search(r'[?&]page=(\d+)>; rel="last"', headers.get("Link", ""))
    return int(m.group(1)) if m else len(body)


