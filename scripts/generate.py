def esc(s):
    return html.escape(str(s), quote=True)


def text_width(s, size, bold=False, mono=False):
    """Estimated width in px. Conservative: fonts differ between systems."""
    return len(s) * size * (0.62 if mono else 0.6 if bold else 0.55)


def wrap(s, size, width, bold=False):
    lines, cur = [], ""
    for word in s.split():
        trial = f"{cur} {word}".strip()
        if cur and text_width(trial, size, bold) > width:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return lines


def fmt_day(d):
    month = S["months"][d.month - 1]
    return f"{month} {d.day}" if S is STRINGS["en"] else f"{d.day} {month}"


def fmt_date(iso):
    return fmt_day(dt.datetime.fromisoformat(iso.replace("Z", "+00:00")))


def fmt_full(d):
    return f"{fmt_day(d)}, {d.year}" if S is STRINGS["en"] else f"{fmt_day(d)} {d.year}"


def t(x, y, s, size=13, cls="t1", weight=None, anchor=None, extra="", mono=False):
    font = "m" if mono else "f"
    attrs = f'x="{x}" y="{y}" font-size="{size}" class="{font} {cls}"'
    if weight:
        attrs += f' font-weight="{weight}"'
    if anchor:
        attrs += f' text-anchor="{anchor}"'
    return f"<text {attrs} {extra}>{esc(s)}</text>"


def svg(w, h, title, body, defs=""):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
        f'role="img" aria-label="{esc(title)}"><title>{esc(title)}</title>{style()}'
        f"<defs>{defs}</defs>{body}</svg>\n"
    )


def shell(w, h, rx=16, title=""):
    """Card frame: glows (glass) or a window with a title bar (terminal). Returns (defs, body)."""
    fw, fh = w - 2 * M, h - 2 * M
    rx = 10 if term() else rx
    defs = f'<clipPath id="fc"><rect x="{M}" y="{M}" width="{fw}" height="{fh}" rx="{rx}"/></clipPath>'
    frame = f'<rect x="{M}.5" y="{M}.5" width="{fw - 1}" height="{fh - 1}" rx="{rx}" class="frame" stroke-width="1"/>'
    if term():
        cy = M + BAR // 2
        body = (
            frame
            + f'<g clip-path="url(#fc)"><rect x="{M}" y="{M}" width="{fw}" height="{BAR}" class="bar"/></g>'
            + f'<line x1="{M}" y1="{M + BAR}.5" x2="{w - M}" y2="{M + BAR}.5" class="sep" stroke-width="1"/>'
            + "".join(f'<circle cx="{M + 18 + i * 16}" cy="{cy}" r="5" class="k{i + 1}"/>' for i in range(3))
            + (t(w // 2, cy + 4, title, 11.5, "t2", anchor="middle", mono=True) if title else "")
        )
        return defs, body
    defs += "".join(
        f'<radialGradient id="{i}"><stop offset="0" class="{i}a"/><stop offset="1" class="{i}b"/></radialGradient>'
        for i, _, _ in GLOW_IDS
    )
    rx_, ry_ = min(w * 0.30, 280), h * 0.85
    glows = "".join(
        f'<ellipse cx="{w * fx:.0f}" cy="{h * fy:.0f}" rx="{rx_:.0f}" ry="{ry_:.0f}" fill="url(#{i})"/>'
        for i, fx, fy in GLOW_IDS
    )
    return defs, frame + f'<g clip-path="url(#fc)">{glows}</g>'


