def main():
    global TOKEN, ROOT, ASSETS, THEME, ACCENT, S, OY
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", help="folder with data/profile.json (default: parent of scripts/)")
    args = parser.parse_args()
    if args.root:
        ROOT = Path(args.root).resolve()
        ASSETS = ROOT / "assets"

    cfg = json.loads((ROOT / "data" / "profile.json").read_text(encoding="utf-8-sig"))  # tolerates a BOM
    THEME = cfg.get("theme", "glass")
    ACCENT = cfg.get("accent", "cyan")
    S = STRINGS[cfg.get("lang", "en")]
    OY = BAR - 4 if term() else 0
    TOKEN = get_token()
    login = cfg["login"]
    ignore = set(cfg.get("languages_ignore", []))
    today = dt.datetime.now(dt.timezone.utc).date()
    ASSETS.mkdir(exist_ok=True)

    user = graphql(
        """query($login:String!){user(login:$login){followers{totalCount}
            contributionsCollection{totalPullRequestContributions
              contributionCalendar{totalContributions weeks{contributionDays{date contributionCount}}}}}}""",
        {"login": login},
    )["user"]
    contrib = user["contributionsCollection"]

    owned = [r for r in rest_all(f"/users/{login}/repos?type=owner") if not r["fork"]]
    repos = {r["full_name"] for r in owned} | {p["repo"] for p in cfg["projects"]}

    totals = {}
    for repo in sorted(repos):
        langs, _ = rest(f"/repos/{repo}/languages")
        for k, v in langs.items():
            totals[k] = totals.get(k, 0) + v
    segments = lang_segments(totals, ignore)
    ignored = [k for k in sorted(ignore) if k in totals]

    infos, layouts = {}, {}
    inner = CARD_W - 2 * (M + 22)
    for p in cfg["projects"]:
        meta, _ = rest(f"/repos/{p['repo']}")
        langs, _ = rest(f"/repos/{p['repo']}/languages")
        x, bar_segs = M, []
        for name, frac in lang_segments(langs, ignore):
            w = (CARD_W - 2 * M) * frac
            bar_segs.append((name, x, w))
            x += w
        infos[p["repo"]] = {"commits": commit_count(p["repo"]), "pushed_at": meta["pushed_at"], "bar": bar_segs}
        layouts[p["repo"]] = project_layout(p, inner)
    max_lines = max(len(l[0]) for l in layouts.values())
    max_rows = max(l[2] for l in layouts.values())
    card_h = card_height(max_lines, max_rows)

    files = {"header.svg": build_header(cfg, login)}
    for i, p in enumerate(cfg["projects"], 1):
        desc, chips, _ = layouts[p["repo"]]
        files[f"project-{i}.svg"] = build_project(p, infos[p["repo"]], (desc, chips, max_lines, max_rows, card_h))
    files["languages.svg"] = build_languages(segments, ignored)
    files["toolkit.svg"] = build_toolkit(cfg["toolkit"])

    calendar = contrib["contributionCalendar"]
    metrics = {
        "repos": len(repos),
        "contributions": calendar["totalContributions"],
        "prs": contrib["totalPullRequestContributions"],
        "stars": sum(r["stargazers_count"] for r in owned),
        "followers": user["followers"]["totalCount"],
        "production": sum(1 for p in cfg["projects"] if p["kind"] == "prod"),
    }
    colors = ("c-blue", "c-cyan", "c-purple", "c-green")
    tiles = [(S[f"tile_{k}"], metrics[k], colors[i]) for i, k in enumerate(cfg.get("tiles", ["repos", "contributions", "prs", "production"]))]
    files["profile-signal.svg"] = build_profile_signal(tiles, today)
    files["consistency-signal.svg"] = build_consistency(calendar["weeks"][-52:], calendar["totalContributions"])

    for name, content in files.items():
        (ASSETS / name).write_text(content, encoding="utf-8")
        print(f"  assets/{name}  ({len(content) // 1024 or 1} KB)")
    if cfg.get("readme", True):
        build_readme(cfg)
        print("  README.md")
    build_preview()
    print("  preview.html")


if __name__ == "__main__":
    main()
