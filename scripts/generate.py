def build_preview():
    """Local page imitating GitHub's README column. Images are inlined: file:// cannot resolve them."""
    def inline(m):
        data = base64.b64encode((ROOT / m.group(1)).read_bytes()).decode()
        return f'src="data:image/svg+xml;base64,{data}"'

    readme = re.sub(r'src="(assets/[^"]+\.svg)"', inline, (ROOT / "README.md").read_text(encoding="utf-8"))
    out = []
    for line in readme.splitlines():
        m = re.match(r"##\s+(.*)", line)
        # a blank line separates paragraphs on GitHub; mimic it so inline tags don't merge
        out.append(f"<h2>{m.group(1)}</h2>" if m else line if line.strip() else '<div style="height:10px"></div>')
    (ROOT / "preview.html").write_text(PREVIEW.replace("{{CONTENT}}", "\n".join(out)), encoding="utf-8")


