def layout_chips(labels, x0, max_x, size=12, pad=9, gap=6):
    x, row, out = x0, 0, []
    for label in labels:
        w = text_width(label, size) * 0.95 + 2 * pad
        if x + w > max_x and x > x0:
            row += 1
            x = x0
        out.append((label, x, row, w))
        x += w + gap
    return out, row + 1


def draw_chips(items, y0, h=24, row_gap=6, size=12, pill=False, tcls="t1"):
    parts = []
    for label, x, row, w in items:
        y = y0 + row * (h + row_gap)
        rx = 4 if term() else (h / 2 if pill else 6)
        cls = "pill" if pill else "chip"
        parts.append(f'<rect x="{x:.1f}" y="{y}" width="{w:.1f}" height="{h}" rx="{rx}" class="{cls}" stroke-width="1"/>')
        parts.append(t(f"{x + w / 2:.1f}", y + h / 2 + 4.2, label, size, tcls, "600" if pill else None, anchor="middle"))
    return "".join(parts)


def milestone(v):
    for m in (10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000):
        if v <= m:
            return m
    return v


def bar(x, y, w, h, frac, cls=None, color=None):
    """Progress bar: rounded (glass) or segmented blocks (terminal)."""
    frac = min(1, max(frac, 0.03))
    fill = f'class="{cls}"' if cls else f'fill="{color}"'
    if term():
        n, gap = 24, 2
        seg = (w - gap * (n - 1)) / n
        on = max(1, round(frac * n))
        return "".join(
            f'<rect x="{x + i * (seg + gap):.1f}" y="{y}" width="{seg:.1f}" height="{h}" rx="1" '
            + (fill if i < on else 'class="track"') + "/>"
            for i in range(n)
        )
    return (
        f'<rect x="{x:.1f}" y="{y}" width="{w:.1f}" height="{h}" rx="{h / 2}" class="track"/>'
        f'<rect x="{x:.1f}" y="{y}" width="{w * frac:.1f}" height="{h}" rx="{h / 2}" {fill}/>'
    )


def donut(cx, cy, r, frac, color):
    c = 2 * math.pi * r
    return (
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke-width="6" class="trk"/>'
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{color}" stroke-width="6" '
        f'stroke-linecap="{"butt" if term() else "round"}" '
        f'stroke-dasharray="{c * frac:.1f} {c:.1f}" transform="rotate(-90 {cx} {cy})"/>'
        + t(cx, cy + 3.8, f"{frac * 100:.0f}%", 10.5, "t1", "700", "middle")
    )


def image_info(raw):
    """(mime, width, height) of a JPEG, PNG or WebP, read from its header without dependencies."""
    if raw[:3] == b"\xff\xd8\xff":
        i = 2
        while i < len(raw):
            marker = raw[i + 1]
            length = int.from_bytes(raw[i + 2:i + 4], "big")
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                return "image/jpeg", int.from_bytes(raw[i + 7:i + 9], "big"), int.from_bytes(raw[i + 5:i + 7], "big")
            i += 2 + length
    if raw[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png", int.from_bytes(raw[16:20], "big"), int.from_bytes(raw[20:24], "big")
    if raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
        chunk = raw[12:16]
        if chunk == b"VP8X":
            return "image/webp", 1 + int.from_bytes(raw[24:27], "little"), 1 + int.from_bytes(raw[27:30], "little")
        if chunk == b"VP8L":
            bits = int.from_bytes(raw[21:25], "little")
            return "image/webp", (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
        if chunk == b"VP8 ":
            return "image/webp", int.from_bytes(raw[26:28], "little") & 0x3FFF, int.from_bytes(raw[28:30], "little") & 0x3FFF
    raise ValueError("portrait must be a JPEG, PNG or WebP file")


