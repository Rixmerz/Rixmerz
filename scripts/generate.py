def level(n, mx):
    if n <= 0:
        return 0
    r = n / mx
    return 1 if r <= 0.25 else 2 if r <= 0.5 else 3 if r <= 0.75 else 4


def build_consistency(weeks, total):
    top, ph = PX, 258
    h = top + ph + 16 + M
    defs, body = shell(W, h, title="git log — activity")
    counts = [d["contributionCount"] for w in weeks for d in w["contributionDays"]]
    body += panel(ph) + titles(top, S["act_title"], S["act_sub"].format(n=total), S["act_cmd"])
    mx = max(counts + [1])
    lx = W - IX
    body += t(lx, top + 40, S["more"], 11.5, "t2", anchor="end")
    for lv in range(4, -1, -1):
        lx -= 14 + (len(S["more"]) * 7 if lv == 4 else 0)
        body += f'<rect x="{lx}" y="{top + 31}" width="11" height="11" rx="2.5" class="h{lv}"/>'
    body += t(lx - 6, top + 40, S["less"], 11.5, "t2", anchor="end")
    cell, gap, y0 = 11, 3, top + 82
    x0 = IX + (IW - (len(weeks) * (cell + gap) - gap)) // 2
    for ci, w in enumerate(weeks):
        for d in w["contributionDays"]:
            row = (dt.date.fromisoformat(d["date"]).weekday() + 1) % 7  # Sunday = 0
            body += (
                f'<rect x="{x0 + ci * (cell + gap)}" y="{y0 + row * (cell + gap)}" width="{cell}" height="{cell}" '
                f'rx="{1.5 if term() else 2.5}" class="h{level(d["contributionCount"], mx)}">'
                f'<title>{d["date"]}: {d["contributionCount"]}</title></rect>'
            )
    active = sum(1 for w in weeks if sum(d["contributionCount"] for d in w["contributionDays"]) > 0)
    streak = best = 0
    for n in counts:
        streak = streak + 1 if n > 0 else 0
        best = max(best, streak)
    col = IW // 3
    sy = y0 + 7 * (cell + gap) + 36
    stats = [
        (f"{active}/{len(weeks)}", S["act_weeks"], "c-blue"),
        (f"{best} {S['days']}", S["act_streak"], "c-cyan"),
        (str(max(counts + [0])), S["act_max"], "c-purple"),
    ]
    for i, (num, label, color) in enumerate(stats):
        body += t(IX + 2 + i * col, sy, num, 24, color, "800", mono=term()) + t(IX + 2 + i * col, sy + 18, label, 12, "t2", "600")
    return svg(W, h, f"{S['act_title']}: {S['act_sub'].format(n=total)}, {active}/{len(weeks)} {S['act_weeks']}", body, defs)


